"""Write docs/traceability/README.md from docs/traceability/requirements.json, or check that it is current.

    python tools/render_requirements.py          rewrite the page from the inventory
    python tools/render_requirements.py --check  verify it and write nothing

The page is generated, never hand-written, as reason-codes.md is from the catalog: one table per
part, then the list of the rules without a vector, which the release bar asks to be public. Each
row quotes the first words of its sentence, or names the table row, so a reader can find the rule;
the inventory itself holds the exact locator.

Exit codes: 0 written or verified, 1 the page is not current, 2 usage error.
"""

from __future__ import annotations

import argparse
import posixpath
import re
import sys
import textwrap
from pathlib import Path

if str(Path(__file__).resolve().parent) not in sys.path:
    sys.path.insert(0, str(Path(__file__).resolve().parent))
import requirements_inventory as inventory_tool  # noqa: E402

COVERAGE_WORDS = {
    "vector": "corpus",
    "excluded": "excluded",
    "suites": "implementation tests only",
    "untested": "not tested",
    "advisory": "advisory",
}


# A Markdown link whose target is relative: no scheme, not rooted.
_RELATIVE_LINK = re.compile(r"\]\((?![a-z][a-z0-9+.-]*:|/)(?P<target>[^)\s]+)\)")


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _relink(text: str, document: str) -> str:
    """``text`` quoted from ``document``, with each relative link made relative to this page.

    A sentence of the specification links its neighbours as `signing-envelope-v2.md`, relative to
    docs/specification/; quoted on docs/traceability/README.md, the same link would point beside
    this page, where no such file is.
    """
    source = posixpath.dirname(f"{inventory_tool.SPECIFICATION}/{document}")
    page = posixpath.dirname(inventory_tool.RENDERED)

    def move(match: re.Match[str]) -> str:
        path, hash_, anchor = match["target"].partition("#")
        target = posixpath.join(source, path) if path else f"{inventory_tool.SPECIFICATION}/{document}"
        return f"]({posixpath.relpath(posixpath.normpath(target), page)}{hash_}{anchor})"

    return _RELATIVE_LINK.sub(move, text)


def _what(record: dict, tables: dict[str, dict]) -> str:
    locator = record["locator"]
    if locator["kind"] == "row":
        table = tables[locator["table"]]
        return f"{table['subject']}: `{locator['key']}`"
    words = inventory_tool.collapse(locator["text"]).split(" ")
    first = " ".join(words[:14])
    return _relink(first, record["document"]) + (" …" if len(words) > 14 else "")


def render(inventory: dict, rule_tables: dict) -> str:
    tables = {table["id"]: table for table in rule_tables["tables"]}
    active = [record for record in inventory["requirements"] if record["status"] == "active"]
    counts = inventory_tool.summary(inventory)
    lines = [
        "# Requirements traceability",
        "",
        "This page is generated by `tools/render_requirements.py` from",
        "[`requirements.json`](requirements.json); edit the inventory, never this page. It is not part of",
        "the specification, and it changes without a protocol release.",
        "",
        "Every requirement the inventory lists has an identifier `REQ-<DOC>-<NNN>` that is never reused",
        "and never renumbered. The identifiers are not written into the specification: a record is bound",
        "to its text by an exact sentence of a section, or by the natural key of a row of a table that",
        "[`rule-tables.json`](rule-tables.json) lists.",
        "",
        "## Scope",
        "",
        textwrap.fill(inventory["scope"], width=100, break_long_words=False, break_on_hyphens=False),
        "",
        "A record is covered by the conformance corpus when it names binding runs of the corpus that",
        f"`{inventory['corpus_lock']}` pins. A test inside an implementation's own suite does not count as",
        "a vector. The maintainer's own tests, carried out with the help of AI tools, the corpus included,",
        "are internal verification and not an audit.",
        "",
        "## Summary",
        "",
        "| where a record stands | records |",
        "| --- | --- |",
    ]
    for key in ("vector", "excluded", "suites", "untested", "advisory"):
        lines.append(f"| {COVERAGE_WORDS[key]} | {counts.get(key, 0)} |")
    lines.append(f"| all active records | {len(active)} |")
    lines.append("")
    for document in inventory_tool.DOC_CODES:
        records = [record for record in active if record["document"] == document]
        if not records:
            continue
        lines += [
            f"## `{document}`",
            "",
            "| id | section | kind | binds | requirement | coverage |",
            "| --- | --- | --- | --- | --- | --- |",
        ]
        for record in records:
            standing = inventory_tool.classify(record)
            coverage = COVERAGE_WORDS[standing]
            if standing == "excluded":
                coverage += f": {record['exclusion']['class']}"
            lines.append(
                f"| {record['id']} | {_cell(record['section'])} | {record['kind']} | {record['binds']} |"
                f" {_cell(_what(record, tables))} | {coverage} |"
            )
        lines.append("")
    lines += [
        "## Rules without a vector",
        "",
        "Every binding record the corpus does not cover is in one of the three lists below; none is left",
        "out. Advisory records carry no obligation and are not listed.",
        "",
        "### Excluded, with the reason",
        "",
        "| id | class | reason |",
        "| --- | --- | --- |",
    ]
    for record in active:
        if inventory_tool.classify(record) == "excluded":
            lines.append(
                f"| {record['id']} | {record['exclusion']['class']} | {_cell(record['exclusion']['reason'])} |"
            )
    lines += [
        "",
        "### Tested only in an implementation or by a check of this repository",
        "",
        "| id | where |",
        "| --- | --- |",
    ]
    for record in active:
        if inventory_tool.classify(record) == "suites":
            where = ", ".join(f"`{entry}`" for entry in record["coverage"]["static"] + record["coverage"]["suites"])
            lines.append(f"| {record['id']} | {_cell(where)} |")
    lines += [
        "",
        "### Not tested, and the known limit",
        "",
        "| id | known limit |",
        "| --- | --- |",
    ]
    for record in active:
        if inventory_tool.classify(record) == "untested":
            lines.append(f"| {record['id']} | {_cell(record.get('known_limit', ''))} |")
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--root", type=Path, default=inventory_tool.ROOT)
    args = parser.parse_args(argv)
    root = args.root
    text = render(inventory_tool.read_inventory(root), inventory_tool.read_rule_tables(root))
    page = root / inventory_tool.RENDERED
    if args.check:
        current = page.read_text(encoding="utf-8") if page.is_file() else None
        if current != text:
            print(f"{inventory_tool.RENDERED} is not the rendering of the inventory; run tools/render_requirements.py")
            return 1
        print("requirements page OK")
        return 0
    page.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {inventory_tool.RENDERED}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
